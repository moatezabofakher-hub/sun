'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const base='app/src/main/assets/www/';
const main=fs.readFileSync(base+'index.html','utf8');
const field=fs.readFileSync('field_agent/src/main/assets/www/index.html','utf8');
const parity=fs.readFileSync('field_agent/src/main/assets/www/static/agent-invoice-parity.js','utf8');
const legacy=fs.readFileSync('field_agent/src/main/assets/www/static/agent-experience.js','utf8');
const check=(folder,html)=>{
  const css=fs.readFileSync(folder+'static/invoice-customer-highlight-3556.css','utf8');
  assert(html.includes('static/invoice-customer-highlight-3556.css'),'Customer styling must be loaded');
  assert(css.includes('.ta-invoice-party-highlight .ta-invoice-party-select'),'Only the customer field should be styled');
  assert.match(css,/background:linear-gradient\(150deg,#e8fff5 0%,#bff7e5 58%,#d2f5f0 100%\)/);
  assert.match(css,/border:2px solid #0b907e!important/);
  assert.match(css,/:focus-within/);
  assert.match(css,/@media\(max-width:370px\)/);
};
check(base,main);
check('field_agent/src/main/assets/www/',field);
assert(main.includes('min-w-0 ta-invoice-party-highlight'));
assert(main.includes('aria-label="${partyLabelAr}" onchange="InvoiceController.changeInvoiceAccount(this.value)" class="ta-invoice-party-select'));
assert(main.includes("const partyLabelAr = isPurchase ? 'المورد' : 'العميل'"),'Purchase/sale party handling unchanged');
assert(parity.includes('min-w-0 ta-invoice-party-highlight'));
assert(parity.includes('id="fAccount" aria-label="العميل" class="ta-invoice-party-select'));
assert(parity.includes('onchange="Agent.accountPricingChanged(this.value)"'),'Account-change handler preserved');
assert(legacy.includes('wide ta-invoice-party-highlight'));
assert(legacy.includes('id="fAccount" aria-label="الزبون" class="field ta-invoice-party-select"'));
const mainVersion=fs.readFileSync('app/build.gradle','utf8');
const agentVersion=fs.readFileSync('field_agent/build.gradle','utf8');
assert.match(mainVersion,/versionName '3\.5\.\d+[^']*'/);
assert.match(agentVersion,/versionName '3\.5\.56-field-customer-highlight'/);
console.log('PASS: customer/supplier selector visually highlighted in manager, agent and fallback invoice forms');
