'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const read = p => fs.readFileSync(p, 'utf8');
const main = read('app/src/main/assets/www/index.html');
const java = read('app/src/main/java/com/sunshine/accounting/MainActivity.java');
const gradle = read('app/build.gradle');
const agentGradle = read('field_agent/build.gradle');
const managerCSS = read('app/src/main/assets/www/static/glossy-ui-3549.css');
const fieldCSS = read('field_agent/src/main/assets/www/static/glossy-ui-3549.css');
const snippet = main.slice(main.indexOf('const InstalledAppVersion = {'), main.indexOf('const AppNav = {'));
assert(snippet.startsWith('const InstalledAppVersion = {'));
const ctx = {window:{Android:{getAppVersionName:()=>'3.5.50-navigation-version-fix'}}};
vm.createContext(ctx);
assert.equal(vm.runInContext(snippet+';InstalledAppVersion.number()',ctx),'3.5.50');
ctx.window.Android.getAppVersionName = () => '3.5.51-other-release';
assert.equal(vm.runInContext('InstalledAppVersion.number()',ctx),'3.5.51','Next versions must be automatic');
ctx.window.Android.getAppVersionName = () => {throw Error('no native connection')};
assert.equal(vm.runInContext('InstalledAppVersion.number()',ctx),'—','No misleading old number');
assert(main.includes('data-app-build="${InstalledAppVersion.number()}"'));
assert(main.includes('إصدار التطبيق: ${InstalledAppVersion.number()}'));
assert(!main.includes('إصدار التطبيق: 3.5.43'));
assert(java.includes('public String getAppVersionName()'));
assert.match(gradle,/versionName '3\.5\.\d+[^']*'/);
assert.match(agentGradle,/versionName '3\.5\.\d+-field-[^']*'/);
assert(managerCSS.includes('width:40px;height:40px;font-size:23px!important'));
assert(managerCSS.includes('@media(max-width:355px)'));
assert(managerCSS.includes('width:36px;height:36px;font-size:21px!important'));
assert(fieldCSS.includes('width:40px;height:40px;border-radius:12px'));
assert(fieldCSS.includes('font-size:27px'));
assert(main.includes('grid-cols-6 h-14'),'Keep previous compact 56px navigation');
console.log('PASS 3.5.50 native Android version in settings and enlarged bottom icons in both apps');
